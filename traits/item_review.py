def survey_items(survey):
    """실제 응답자에게 노출되는 문항을 Survey.schema에서 순서대로 추출한다."""
    items = []
    for page in (survey.schema or {}).get('pages', []):
        for element in page.get('elements', []):
            title = element.get('title')
            if title:
                items.append(str(title))
    return items or list(QUESTION_TEXT)


def build_item_review_prompt(items):
    numbered = '\n'.join(f'{no}. {text}' for no, text in enumerate(items, 1))
    return (
        f'{PROMPT_BODY}\n\n'
        '# 검토할 문항\n\n'
        f'아래에 {len(items)}개 문항을 입력합니다.\n\n'
        f'{numbered}\n'
    )
