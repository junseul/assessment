def score_band(score):
    """0~100 점수를 (band_key, band_label)로 변환. 점수 없으면 (None, None)."""
    if score is None:
        return None, None
    for key, label, minimum in BANDS:
        if score >= minimum:
            return key, label
    return 'low', '낮은 수준'


def describe_domain(domain_key, score):
    """도메인 키와 점수로 해석 문구 반환. 점수 없으면 None."""
    band, _ = score_band(score)
    if band is None:
        return None
    return DOMAIN_DESCRIPTIONS[domain_key][band]


def percentile_rank(values, score):
    """규준 점수 리스트에서 score의 백분위(0~100, 정수). 동점은 절반만 반영.

    백분위 p는 "전체 응시자의 p%가 이 점수 이하"를 의미한다.
    규준이 없으면 None.
    """
    if score is None or not values:
        return None
    below = sum(1 for value in values if value < score)
    ties = sum(1 for value in values if value == score)
    return round((below + ties / 2) / len(values) * 100)
